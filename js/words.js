// Стабильные ID: hash(t::w::a), не зависят от порядка в массиве.
// При перестановке слов прогресс остаётся привязан к правильным записям.
const _seenIds = new Set();
for (const w of WORDS) {
  let base = "w_" + hashString(`${w.t}::${w.w}::${w.a}`);
  let id = base, n = 1;
  while (_seenIds.has(id)) { n++; id = base + "_" + n; }
  w.id = id;
  _seenIds.add(id);
}